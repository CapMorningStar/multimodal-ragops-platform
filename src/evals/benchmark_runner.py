"""Automated RAGOps CI/CD Benchmark Runner."""

import argparse
import json
import logging
from pathlib import Path
from typing import Any, Dict, List, Optional

from config.logging_config import configure_logging
from src.crag.graph import run_crag
from src.evals.latency_tracer import LatencyTracer
from src.evals.ragas_eval import EvaluationReport, EvaluationSample, RagasEvaluator
from src.vector_store.local_store import LocalVectorStore

logger = logging.getLogger(__name__)

# Default synthetic golden benchmark dataset for financial/enterprise RAG
DEFAULT_BENCHMARK_PROMPTS = [
    {
        "question": "What was the total operating revenue for Alphabetical Enterprise Group in fiscal 2026?",
        "ground_truth": "Operating revenue was $124.6 billion, representing a 21.8% year-over-year increase.",
    },
    {
        "question": "What was the operating margin in fiscal 2026 and how many basis points did it expand?",
        "ground_truth": "Operating margin reached 29.1%, expanding by 110 basis points.",
    },
    {
        "question": "What was the total capital expenditure (CapEx) allocated for fiscal 2026?",
        "ground_truth": "Total capital deployment was $28.5 billion in FY2026.",
    },
    {
        "question": "How much revenue was generated by Cloud and AI Infrastructure in FY2026?",
        "ground_truth": "Cloud & AI Infrastructure generated $58.5 billion, growing 39.3% YoY.",
    },
]


class BenchmarkRunner:
    """Orchestrates end-to-end evaluation runs and exports regression reports."""

    def __init__(
        self,
        vector_store: Optional[LocalVectorStore] = None,
        evaluator: Optional[RagasEvaluator] = None,
    ):
        self.vector_store = vector_store or LocalVectorStore()
        self.evaluator = evaluator or RagasEvaluator()

    def run_benchmark(
        self,
        test_prompts: Optional[List[Dict[str, str]]] = None,
        report_path: Optional[Path] = None,
    ) -> EvaluationReport:
        """Executes test suite through CRAG and evaluates results."""
        prompts = test_prompts or DEFAULT_BENCHMARK_PROMPTS
        samples: List[EvaluationSample] = []
        tracer = LatencyTracer()

        logger.info(f"Running RAGOps benchmark on {len(prompts)} test queries...")

        for item in prompts:
            q = item["question"]
            gt = item.get("ground_truth")

            with tracer.trace_step(f"query:{q[:20]}"):
                result_state = run_crag(query=q, vector_store=self.vector_store)

            contexts = [d.get("content", "") for d in result_state.get("retrieved_docs", [])]
            answer = result_state.get("final_response", "")

            samples.append(
                EvaluationSample(
                    question=q,
                    contexts=contexts,
                    answer=answer,
                    ground_truth=gt,
                )
            )

        report = self.evaluator.evaluate_dataset(samples)
        trace_summary = tracer.get_summary()

        # Generate Markdown Report
        md_content = [
            "# RAGOps CI/CD Benchmark Report",
            "",
            "## Summary Metrics",
            f"- **Status**: {'PASSED' if report.passed else 'FAILED'}",
            f"- **Total Test Cases**: {report.total_samples}",
            f"- **Faithfulness**: `{report.faithfulness:.4f}` (Gate: >= 0.8500)",
            f"- **Answer Relevance**: `{report.answer_relevance:.4f}` (Gate: >= 0.8000)",
            f"- **Context Precision**: `{report.context_precision:.4f}`",
            f"- **Overall Average**: `{report.average_score:.4f}`",
            "",
            "## Latency & Resource Telemetry",
            f"- **Total Benchmark Duration**: `{trace_summary.total_duration_ms:.2f} ms`",
            f"- **Estimated Token Cost**: `${trace_summary.total_cost_usd:.6f}`",
            "",
            "## Detailed Test Cases",
            "| Index | Question | Faithfulness | Relevance | Precision |",
            "| :--- | :--- | :--- | :--- | :--- |",
        ]

        for i, (p, sc) in enumerate(zip(prompts, report.sample_scores), 1):
            md_content.append(
                f"| {i} | {p['question'][:40]}... | {sc['faithfulness']:.2f} | {sc['answer_relevance']:.2f} | {sc['context_precision']:.2f} |"
            )

        out_md = report_path or Path("./eval_report.md")
        with open(out_md, "w", encoding="utf-8") as f:
            f.write("\n".join(md_content) + "\n")

        logger.info(f"Generated benchmark report at: {out_md}")
        return report


def main() -> None:
    """CLI entrypoint for running benchmark suite."""
    configure_logging()
    parser = argparse.ArgumentParser(description="RAGOps Benchmark Runner")
    parser.add_argument("--output", type=str, default="eval_report.md", help="Output report path")
    args = parser.parse_args()

    runner = BenchmarkRunner()
    report = runner.run_benchmark(report_path=Path(args.output))

    if not report.passed:
        logger.error("RAGOps benchmark gate FAILED! Scores did not meet minimum thresholds.")
        exit(1)
    else:
        logger.info("RAGOps benchmark gate PASSED!")


if __name__ == "__main__":
    main()
